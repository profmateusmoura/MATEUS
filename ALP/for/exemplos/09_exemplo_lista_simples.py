"""Exemplo 9: percorrendo uma lista simples.

Explicação:
A estrutura for também funciona com listas.

for nome in nomes:
    print(nome)

Aqui:
- nomes é a lista
- nome recebe cada elemento da lista em cada repetição
- a sequência será: "Ana", "Bruno", "Carla", "Davi"
"""

nomes = ["Ana", "Bruno", "Carla", "Davi"]

for nome in nomes:
    print(nome)
